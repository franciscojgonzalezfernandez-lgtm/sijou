/**
 * URL slug from a product name (F-010 CA-6): lowercase ASCII letters, digits and single hyphens.
 * German umlauts are spelled out (ä → ae) so German slugs stay readable; other accents are dropped.
 */
export function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/ä/g, "ae")
    .replace(/ö/g, "oe")
    .replace(/ü/g, "ue")
    .replace(/ß/g, "ss")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
